package repo

import (
	"database/sql"
	"fmt"
)

type UserRepo struct {
	db *sql.DB
}

func NewUserRepo(db *sql.DB) *UserRepo {
	return &UserRepo{db: db}
}

func (r *UserRepo) SearchByName(name string) ([]string, error) {
	rows, err := r.db.Query(fmt.Sprintf("SELECT name FROM users WHERE name LIKE '%%%s%%'", name))
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []string
	for rows.Next() {
		var n string
		rows.Scan(&n)
		out = append(out, n)
	}
	return out, nil
}
